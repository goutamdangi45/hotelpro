const jwt = require('jsonwebtoken');
const User = require('../models/User');

// Helper function to sign JWT
const signToken = (id) => {
  return jwt.sign(
    { id },
    process.env.JWT_SECRET || 'hotelpro_super_secret_jwt_key_2026_modern_secure_token',
    {
      expiresIn: process.env.JWT_EXPIRE || '30d',
    }
  );
};

// @desc    Register a new user
// @route   POST /api/auth/register
// @access  Public
exports.register = async (req, res, next) => {
  try {
    const { name, email, password, phone, role, idProofType, idProofNumber } = req.body;

    if (!name || !email || !password) {
      return res.status(400).json({
        success: false,
        message: 'Please provide full name, email, and password',
      });
    }

    // Check if user already exists
    const existingUser = await User.findOne({ email });
    if (existingUser) {
      return res.status(400).json({
        success: false,
        message: 'An account with this email address already exists',
      });
    }

    // Prevent random users from claiming admin role directly unless specified in development or authorized
    let assignedRole = 'guest';
    if (role && ['guest', 'staff'].includes(role)) {
      assignedRole = role;
    }

    const user = await User.create({
      name,
      email,
      password,
      phone: phone || '',
      role: assignedRole,
      idProofType: idProofType || '',
      idProofNumber: idProofNumber || '',
    });

    const token = signToken(user._id);

    res.status(201).json({
      success: true,
      token,
      user: {
        _id: user._id,
        name: user.name,
        email: user.email,
        role: user.role,
        phone: user.phone,
        avatar: user.avatar,
        idProofType: user.idProofType,
        idProofNumber: user.idProofNumber,
      },
      message: 'Account registered successfully',
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Login user
// @route   POST /api/auth/login
// @access  Public
exports.login = async (req, res, next) => {
  try {
    const { email, password } = req.body;

    if (!email || !password) {
      return res.status(400).json({
        success: false,
        message: 'Please enter both email and password',
      });
    }

    const user = await User.findOne({ email }).select('+password');
    if (!user) {
      return res.status(401).json({
        success: false,
        message: 'Invalid credentials. User not found.',
      });
    }

    const isMatch = await user.comparePassword(password);
    if (!isMatch) {
      return res.status(401).json({
        success: false,
        message: 'Invalid credentials. Password does not match.',
      });
    }

    const token = signToken(user._id);

    res.status(200).json({
      success: true,
      token,
      user: {
        _id: user._id,
        name: user.name,
        email: user.email,
        role: user.role,
        phone: user.phone,
        address: user.address,
        avatar: user.avatar,
        idProofType: user.idProofType,
        idProofNumber: user.idProofNumber,
        vipStatus: user.vipStatus,
      },
      message: 'Logged in successfully',
    });
  } catch (error) {
    next(error);
  }
};

